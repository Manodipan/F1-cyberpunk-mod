#!/usr/bin/env python3
"""
Generate the "explicit gears" experiment: the deliverable YAML with one block changed.

Why: our `vehEngineData` inherits `Vehicle.VehicleEngineData_4_SuperSport` and then does
`8 × !remove` of that record's inline gears followed by `8 × !append` of ours. If any of
those removes misses (record renamed in a game patch, inline id spelled differently), the
inherited list survives in front of ours — and the car behaves like the car it inherited
from. The Jesko Attack reference (`reference/vehicles/jesko_attack/jesko_attack.yaml`) does not do this
at all: its engine data carries one explicit `gears: [ ... ]` list.

This emits that form for us, changing nothing else:

    python tools/engine_explicit.py            # writes experiments/phoenix_engine_explicit.yaml

Install (game copy, after backing up):

    $d = "G:\\Cyberpunk2077\\Cyberpunk 2077 Phantom Liberty\\r6\\tweaks\\phoenix"
    Copy-Item "$d\\phoenix_aston_valkyrie.yaml" "$d\\phoenix_aston_valkyrie.yaml.stock" -Force
    Copy-Item "$HOME\\f1-cyberpunk-mod\\experiments\\phoenix_engine_explicit.yaml" "$d\\phoenix_aston_valkyrie.yaml" -Force

Restart the game. Revert by copying the `.stock` file back.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "Phoenix_aston_cheats" / "r6" / "tweaks" / "phoenix" / "phoenix_aston_valkyrie.yaml"
OUT = ROOT / "experiments" / "phoenix_engine_explicit.yaml"

GEAR_ORDER = ["r", "1", "2", "3", "4", "5", "6", "7"]


def indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def transform(text: str) -> str:
    lines = text.split("\n")

    # the inline engine block inside Vehicle.phoenix_aston_valkyrie
    start = next((i for i, l in enumerate(lines) if re.match(r"^\s+vehEngineData:\s*$", l)), None)
    if start is None:
        raise SystemExit("could not find the vehEngineData block")
    base_indent = indent_of(lines[start])

    end = len(lines)
    for i in range(start + 1, len(lines)):
        if lines[i].strip() and indent_of(lines[i]) <= base_indent:
            end = i
            break

    # the gears: field inside it
    g = next((i for i in range(start + 1, end) if re.match(r"^\s+gears:\s*$", lines[i])), None)
    if g is None:
        raise SystemExit("could not find the gears: field inside vehEngineData")
    g_indent = indent_of(lines[g])

    g_end = end
    for i in range(g + 1, end):
        if lines[i].strip() and indent_of(lines[i]) <= g_indent:
            g_end = i
            break

    children = lines[g + 1:g_end]
    tags = [c for c in children if "!append" in c or "!remove" in c]
    if not tags:
        raise SystemExit("gears: is already an explicit list - nothing to do")

    # tagged lines elsewhere *inside the engine block* would mean the shape changed.
    # (Tags outside it - the vehicle_list registration - are none of our business.)
    inside = lines[start + 1:g] + lines[g_end:end]
    stray = [l for l in inside if "!append" in l or "!remove" in l]
    if stray:
        raise SystemExit(f"{len(stray)} tagged line(s) elsewhere in vehEngineData - refusing to guess")

    gear_list = ", ".join(f"Vehicle.phoenix_amv_gear_{g}" for g in GEAR_ORDER)
    replacement = [f"{' ' * g_indent}gears: [ {gear_list} ]"]

    lines[g:g_end] = replacement
    return "\n".join(lines)


def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    out = transform(text)
    header = (
        "# GENERATED by tools/engine_explicit.py from Phoenix_aston_cheats/r6/tweaks/phoenix/\n"
        "# phoenix_aston_valkyrie.yaml - do not edit by hand, re-run the tool instead.\n"
        "#\n"
        "# ONE difference from the deliverable: vehEngineData carries an explicit gears list\n"
        "# instead of 8x !remove + 8x !append on the inherited SuperSport gear set.\n"
        "# Experiment for the 330 km/h plateau - see docs/TOPSPEED-TEST.md.\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + out, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}  ({len(out.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
