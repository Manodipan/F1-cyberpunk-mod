#!/usr/bin/env python3
"""
Derive the Phoenix's top-speed design point from the real cars that actually went there.

    python3 tools/land_speed_design.py           # rewrite docs/TOPSPEED-DESIGN.md
    python3 tools/land_speed_design.py --check   # fail if the doc is stale

Every record car below is checked against P = 1/2 rho CdA v^3 + rolling, so the model earns its
right to predict our own car. Standard sea-level air, 1.225 kg/m^3.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "TOPSPEED-DESIGN.md"
RHO = 1.225
G = 9.81
CRR = 0.015                     # rolling resistance coefficient, road tyres

# name, power kW, Cd, frontal area m^2, mass kg, record speed km/h, notes
RECORDS = [
    ("Koenigsegg Jesko Absolut", 1193, 0.278, 1.88, 1390, None,
     "no official run; 531-563 claimed"),
    ("SSC Tuatara", 1305, 0.279, 1.672, 1247, 532.93,
     "one-way Vmax, 2020 (508.73 two-way)"),
    ("Bugatti Chiron SS 300+", 1177, 0.350, 2.40, 1995, 490.484,
     "Ehre-Lessien, 2019"),
    ("Koenigsegg Agera RS", 1000, 0.330, 1.87, 1395, 447.19,
     "two-way average, Nevada 2017"),
]

# The game's fields we are choosing, and what the control car does with them.
GAME_REF = {"airResistanceFactor": 0.66, "engineMaxTorque": 1000,
            "mass": 1800, "top_gear_mps": 78.5}
CONTROL_TOP_KMH = 278.0         # measured, timed over 1 km
PHOENIX_MASS = 1800             # the Jesko's, which the control uses
TARGET_KMH = 500.0


def drag_power(v, cda, mass):
    """Watts needed to hold v m/s: aero + rolling."""
    return 0.5 * RHO * cda * v ** 3 + CRR * mass * G * v


def v_for_power(p_w, cda, mass):
    """Equilibrium speed in m/s from a bisection on drag_power."""
    lo, hi = 1.0, 250.0
    for _ in range(200):
        mid = (lo + hi) / 2
        if drag_power(mid, cda, mass) < p_w:
            lo = mid
        else:
            hi = mid
    return lo


def kw(p_w):
    return p_w / 1000.0


def hp(p_w):
    return p_w / 745.7


def table_records():
    rows = ["| car | power | Cd | A (m²) | CdA | record | model says | error | note |",
            "|---|---|---|---|---|---|---|---|---|"]
    for name, p_kw, cd, area, mass, record, note in RECORDS:
        cda = cd * area
        v_eq = v_for_power(p_kw * 1000, cda, mass)
        if record:
            err = (v_eq * 3.6 - record) / record * 100
            rec = f"{record:.1f} km/h"
            err_s = f"**{err:+.1f}%**"
        else:
            rec = "—"
            err_s = "—"
        rows.append(f"| {name} | {p_kw} kW ({hp(p_kw*1000):.0f} hp) | {cd:.3f} | {area:.2f} | "
                    f"{cda:.3f} | {rec} | {v_eq*3.6:.0f} km/h | {err_s} | {note} |")
    return "\n".join(rows)


def table_target():
    rows = ["| CdA | aero power at 500 | + rolling | total | needs | from the record cars |",
            "|---|---|---|---|---|---|"]
    for cda, src in ((0.466, "Tuatara's 0.279 x 1.672 m²"),
                     (0.523, "Jesko Absolut's 0.278 x 1.88 m²"),
                     (0.617, "Agera RS's 0.330 x 1.87 m²"),
                     (0.760, "Chiron's *effective* CdA at its record"),
                     (GAME_REF["airResistanceFactor"], "the control car's airResistanceFactor")):
        v = TARGET_KMH / 3.6
        aero = 0.5 * RHO * cda * v ** 3
        roll = CRR * PHOENIX_MASS * G * v
        rows.append(f"| {cda:.3f} | {kw(aero):.0f} kW | {kw(roll):.0f} kW | "
                    f"**{kw(aero+roll):.0f} kW ({hp(aero+roll):.0f} hp)** | "
                    f"{hp(aero+roll):.0f} hp | {src} |")
    return "\n".join(rows)


def table_force():
    """How much more force the top gear needs, relative to the control car's measured 278."""
    v0 = CONTROL_TOP_KMH / 3.6
    v1 = TARGET_KMH / 3.6
    stretch = v1 / GAME_REF["top_gear_mps"]
    rows = ["| target CdA | aero force at 500 | vs control's force | x gearing stretch | **torque multiplier needed** |",
            "|---|---|---|---|---|"]
    for cda in (0.466, 0.523, 0.617, GAME_REF["airResistanceFactor"]):
        f1 = 0.5 * RHO * cda * v1 ** 2
        f0 = 0.5 * RHO * GAME_REF["airResistanceFactor"] * v0 ** 2
        need = (f1 / f0) * stretch
        rows.append(f"| {cda:.3f} | {f1/1000:.2f} kN | {f1/f0:.2f}x | {stretch:.3f}x | **{need:.2f}x** |")
    return "\n".join(rows)


def build_doc():
    v_target = TARGET_KMH / 3.6
    cda_absolut = 0.278 * 1.88
    v_absolut = v_for_power(1193e3, cda_absolut, 1390) * 3.6
    stretch = v_target / GAME_REF["top_gear_mps"]
    f1 = 0.5 * RHO * cda_absolut * v_target ** 2
    f0 = 0.5 * RHO * GAME_REF["airResistanceFactor"] * (CONTROL_TOP_KMH / 3.6) ** 2
    need = (f1 / f0) * stretch
    torque = GAME_REF["engineMaxTorque"] * need
    return f"""# The 500 km/h design, derived from real cars

Generated by `tools/land_speed_design.py` — do not edit by hand.

Everything below starts from the four road cars that have actually been to 447-533 km/h, checks
the standard drag model against their records, and only then applies it to the Phoenix.

## 1. Does the textbook model describe the real cars?

Power to hold a speed is `P = ½ ρ CdA v³ + Crr·m·g·v`, with ρ = {RHO} kg/m³ and Crr = {CRR}.

{table_records()}

The model reproduces the verified records to a few percent, and where it over-predicts it is
predicting a *terminal* speed the car never got to demonstrate — the Jesko Absolut has never
made an official run, and the Tuatara's driver reported it "still pulling" at 331 mph. So the
model is trustworthy for sizing, and slightly optimistic for claims.

## 2. What does 500 km/h cost?

At 138.9 m/s, for a {PHOENIX_MASS} kg car:

{table_target()}

The class answer for a **real 500 km/h** is a **CdA around 0.52 and roughly 1,150 hp** — which is
exactly the Jesko Absolut, the one car in the set built for nothing else.

## 3. The design point

Adopt the Jesko Absolut's aerodynamics — **CdA {cda_absolut:.3f}** — and the reference engine's
~1,600 hp. That combination's equilibrium is **{v_absolut:.0f} km/h**, so 500 km/h is a *plateau*
the car sits on with margin, not a cliff it falls off. That is how every record car is built: they
exceed the number they are named after.

## 4. What that means for the game's numbers

The game's `airResistanceFactor` cannot be mapped to real CdA from the data we hold. The Jesko's
game value 0.66 sits suspiciously close to its real CdA (0.70), but the stock Valkyrie's 1.35 does
not match its real ~0.63, and the Quadra's 2.45 matches nothing. So the field is *a* drag dial,
not *the* CdA, and it has to be calibrated in-game rather than assumed.

What does transfer is the **ratio to the car we measured**. The control stops at
{CONTROL_TOP_KMH:.0f} km/h ({CONTROL_TOP_KMH/3.6:.1f} m/s). Holding 500 km/h at CdA {cda_absolut:.3f}
needs this much more force than that car was using at its top speed, and taller gearing costs
force in the same measure (the ladder stretches {stretch:.3f}x to reach 138.9 m/s):

- aero force at 500: **{f1/1000:.2f} kN** vs **{f0/1000:.2f} kN** at the control's 278 = {f1/f0:.2f}x
- taller gearing divides wheel force by {stretch:.3f}x
- **net torque multiplier needed: {need:.2f}x** → `engineMaxTorque` {GAME_REF['engineMaxTorque']} → **{torque:.0f}**

{table_force()}

If the control turns out to be **pinned** at its gear ceiling (revs at the limit, engine with
surplus) rather than **faded** (revs below redline, drag equilibrium), then it was not spending
its full force at 278, and the true requirement is lower than {need:.2f}x by however much surplus
it had. That measurement — a look at the revs at 278 — is worth more than any assumption here.

## 5. Gearing rule from the record cars

All four put peak power at, or just below, the record speed: the Chiron makes 1,578 hp at
6,700 rpm with a 6,900 redline and reaches 490 in top; the Jesko Absolut peaks at 7,800 with an
8,500 redline. Nobody gears for redline at Vmax — they gear for the **power peak** at Vmax.

The reference ladder we copied tops gear 7 at 78.5 m/s on a 7,800 rpm ceiling, which is the same
relationship. Stretching it to 138.9 m/s (x{stretch:.3f}) preserves it, as long as the floors stay
at 0.90 of the previous gear's top so consecutive gears always overlap — the trap that stopped
the earlier 350 km/h build was a gap between gears, where no gear could pull.

## 6. The build this predicts

| field | value | why |
|---|---|---|
| `airResistanceFactor` | 0.55 | CdA {cda_absolut:.2f} class; the dial is uncalibrated, so treat as a starting point |
| gear 7 `maxSpeed` | 138.89 | 500 km/h; plateau target is ~{v_absolut:.0f} |
| gear floors | 0.90 x previous top | never leave a gap between gears |
| top rpm ceiling | 7,600 | power peak just below, as the record cars do |
| `engineMaxTorque` | {torque:.0f} | {need:.2f}x the reference, to hold 500 against the drag |
| mass | {PHOENIX_MASS} | the reference's, kept |

## 7. Before believing any of it: the coastdown test

The one unknown is the game's drag scale. It can be measured exactly, in about thirty seconds,
with the instrument we just installed — the true m/s readout:

1. Get to ~200 km/h, lift off, coast in neutral.
2. Note the speed at the moment you lift and again 5 s later.
3. Repeat at a lower starting speed.

Drag deceleration is `a = ½ρ·k·v²/m + Crr·g`, so two speeds separate the drag constant `k` from
rolling resistance. With `k` known, `airResistanceFactor` for CdA 0.52 is arithmetic instead of
guesswork — and the same number then lets us predict the top speed before driving it.
"""


def main(argv):
    doc = build_doc()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != doc:
            print(f"{OUT.relative_to(ROOT)} is stale - run: make design")
            return 1
        print("design doc is current")
        return 0
    OUT.write_text(doc, encoding="utf-8")
    print(f"wrote: {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
